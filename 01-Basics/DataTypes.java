public class DataTypes {

    public static void main(String[] args) {

        // Integer Data Types
        byte age = 20;
        short year = 2025;
        int population = 1400000000;
        long mobileNumber = 9876543210L;

        // Decimal Data Types
        float percentage = 89.5f;
        double pi = 3.14159265359;

        // Character Data Type
        char grade = 'A';

        // Boolean Data Type
        boolean isJavaFun = true;

        // Non-Primitive Data Type
        String name = "Shrutik";

        System.out.println("----- Java Data Types -----");
        System.out.println("Name           : " + name);
        System.out.println("Age (byte)     : " + age);
        System.out.println("Year (short)   : " + year);
        System.out.println("Population(int): " + population);
        System.out.println("Mobile (long)  : " + mobileNumber);
        System.out.println("Percentage(float): " + percentage);
        System.out.println("PI (double)    : " + pi);
        System.out.println("Grade (char)   : " + grade);
        System.out.println("Java Fun?      : " + isJavaFun);
    }
}